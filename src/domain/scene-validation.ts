/**
 * SceneV1 Validation Functions
 *
 * Validates scene structures per PLAN §3.1 data contract:
 * - Required fields present and non-null
 * - Finite values (no NaN/Infinity)
 * - Valid UUIDs (format and uniqueness)
 * - Normalized quaternion [x,y,z,w] representation
 * - Optical parameter ranges within valid bounds
 * - Element references resolve correctly
 */

import {
  BaseElement,
  ElementKind,
  PositionTuple,
  QuaternionTuple,
  SceneV1,
} from './scene';

// Tolerance constants per PLAN §3.1
export const GEOM_TOL = 1e-9;      // Position/meter tolerance
export const ANGLE_TOL = 1e-8;      // Angle/radian tolerance
export const POWER_TOL = 1e-8;      // Power/probability tolerance

/** Validation result type */
export interface ValidationResult {
  valid: boolean;
  errors?: string[];
  uuidCount?: number;
}

/** Check if value is finite (reject NaN/Infinity) */
export function isFiniteNumber(x: unknown): x is number {
  return typeof x === 'number' && Number.isFinite(x);
}

/** Validate UUID format (v4 generated by crypto.randomUUID) */
export function isValidUUID(uuid: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(uuid);
}

/** Normalize vector to unit length */
export function normalizeVector(v: PositionTuple): PositionTuple {
  const len = Math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]);
  if (len < 1e-16) return [0, 0, 0];
  return [v[0] / len, v[1] / len, v[2] / len];
}

/** Validate quaternion [x, y, z, w] is normalized */
export function isValidQuaternion(q: QuaternionTuple): boolean {
  if (!Array.isArray(q) || q.length !== 4) return false;
  if (!q.every(isFiniteNumber)) return false;
  const normSq = q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3];
  return Math.abs(normSq - 1.0) < 1e-6;
}

/** Pose with position tuple and quaternion rotation */
export interface Pose {
  position: PositionTuple;
  orientation: QuaternionTuple;
}

export function isValidPose(pose: Pose): boolean {
  if (!pose || !Array.isArray(pose.position) || pose.position.length !== 3) {
    return false;
  }
  if (!pose.position.every(isFiniteNumber)) return false;
  return isValidQuaternion(pose.orientation);
}

/** Validate TableSpec bounds */
export function validateTable(table: SceneV1['table']): boolean {
  if (!table) return false;
  if (!isFiniteNumber(table.width) || !isFiniteNumber(table.depth) ||
      !isFiniteNumber(table.cellSize)) {
    return false;
  }

  if (table.width <= 0 || table.depth <= 0 || table.cellSize <= 0) {
    return false;
  }

  if (table.width > 10 || table.depth > 10) { // Reasonable max size
    return false;
  }

  return true;
}

/** Validate ViewParams */
export function validateView(camera: SceneV1['camera']): boolean {
  if (!camera) return false;
  if (!isFiniteNumber(camera.fov)) return false;
  if (camera.fov <= 0 || camera.fov > Math.PI) return false;

  const posValid = Array.isArray(camera.position) &&
    camera.position.length === 3 && camera.position.every(isFiniteNumber);
  const tgtValid = Array.isArray(camera.target) &&
    camera.target.length === 3 && camera.target.every(isFiniteNumber);

  return posValid && tgtValid;
}

const VALID_KINDS: readonly ElementKind[] = [
  'source', 'raysSource', 'lens', 'thickLens', 'mirror',
  'polarizer', 'waveplate', 'faraday', 'pbs', 'bs',
  'iris', 'detector', 'beamDump', 'grating',
];

/** Validate individual BaseElement */
export function validateElement(element: BaseElement): boolean {
  if (!element || typeof element !== 'object') return false;

  // Check UUID
  if (typeof element.uuid !== 'string' || !isValidUUID(element.uuid)) {
    return false;
  }

  // Check kind is a valid enum member
  if (!VALID_KINDS.includes(element.kind)) return false;

  // Check pose
  if (!isValidPose(element.pose)) return false;

  // Check mount DOFs are finite and ordered
  if (!element.mount || !Array.isArray(element.mount.pivotPoint) ||
      element.mount.pivotPoint.length !== 3 ||
      !element.mount.pivotPoint.every(isFiniteNumber)) {
    return false;
  }

  if (!element.mount.axes) return false;
  const dofLimits = [
    element.mount.axes.tiltX,
    element.mount.axes.tiltY,
    element.mount.axes.rotationZ,
  ];

  for (const axis of dofLimits) {
    if (!axis || !isFiniteNumber(axis.min) || !isFiniteNumber(axis.max)) return false;
    if (axis.min > axis.max) return false;
    if (Math.abs(axis.max - axis.min) > Math.PI * 2) return false; // Max range ~720°
  }

  // Check active flag
  if (typeof element.active !== 'boolean') return false;

  // Check props (basic validation only)
  if (!element.props || typeof element.props !== 'object') return false;

  switch (element.kind) {
    case 'source':
    case 'raysSource': {
      const { wavelength_nm, forward_cm, backward_cm } = element.props;
      if (!isFiniteNumber(wavelength_nm) || wavelength_nm <= 0) return false;
      if (!isFiniteNumber(forward_cm) || forward_cm < 0) return false;
      if (backward_cm !== undefined &&
          (!isFiniteNumber(backward_cm) || backward_cm < 0)) return false;
      break;
    }

    case 'lens':
    case 'thickLens': {
      const { focalLength_m } = element.props;
      if (!isFiniteNumber(focalLength_m) || focalLength_m === 0) return false;
      break;
    }

    case 'mirror':
    case 'pbs':
    case 'bs':
    case 'beamDump': {
      const { reflectivity } = element.props;
      if (reflectivity !== undefined &&
          (!isFiniteNumber(reflectivity) || reflectivity < 0 || reflectivity > 1)) {
        return false;
      }
      break;
    }

    case 'waveplate':
      if (!isFiniteNumber(element.props.fastAxisAngleDeg)) return false;
      break;

    case 'polarizer':
      if (!isFiniteNumber(element.props.axisAngleDeg)) return false;
      break;

    case 'detector': {
      const { apertureRadius_m, efficiency } = element.props;
      if (!isFiniteNumber(apertureRadius_m) || apertureRadius_m <= 0) return false;
      if (efficiency !== undefined &&
          (!isFiniteNumber(efficiency) || efficiency < 0 || efficiency > 1)) {
        return false;
      }
      break;
    }

    case 'iris': {
      const { radius_m } = element.props;
      if (!isFiniteNumber(radius_m) || radius_m < 0) return false;
      break;
    }
  }

  return true;
}

/** Validate SceneV1 structure */
export function validateScene(scene: SceneV1): ValidationResult {
  if (!scene || typeof scene !== 'object') {
    return { valid: false, errors: ['Scene must be an object'] };
  }

  // Check schemaVersion
  if (scene.schemaVersion !== 1) {
    return {
      valid: false,
      errors: [`Invalid schemaVersion: expected 1, got ${String(scene.schemaVersion)}`],
    };
  }

  // Check sceneId (must exist)
  if (!scene.sceneId || typeof scene.sceneId !== 'string') {
    return { valid: false, errors: ['Missing or invalid sceneId'] };
  }

  // Check revision (must be non-negative integer)
  if (!Number.isInteger(scene.revision) || scene.revision < 0) {
    return { valid: false, errors: ['Invalid revision: must be non-negative integer'] };
  }

  // Check seed (must be finite integer)
  if (!Number.isInteger(scene.seed) || !isFiniteNumber(scene.seed)) {
    return { valid: false, errors: ['Seed must be a finite integer'] };
  }

  // Check table
  if (!validateTable(scene.table)) {
    return { valid: false, errors: ['Invalid table dimensions'] };
  }

  // Check camera
  if (!validateView(scene.camera)) {
    return { valid: false, errors: ['Invalid camera/view parameters'] };
  }

  // Check elements array
  if (!Array.isArray(scene.elements)) {
    return { valid: false, errors: ['Elements must be an array'] };
  }

  // Validate each element and collect UUIDs for uniqueness check
  const uuids = new Set<string>();

  for (let i = 0; i < scene.elements.length; i++) {
    const el = scene.elements[i];

    if (!el || typeof el.uuid !== 'string') {
      return { valid: false, errors: [`Element at index ${i} is missing a UUID`] };
    }

    // Check UUID uniqueness
    if (uuids.has(el.uuid)) {
      return { valid: false, errors: [`Duplicate UUID "${el.uuid}" at index ${i}`] };
    }
    uuids.add(el.uuid);

    // Validate element structure
    if (!validateElement(el)) {
      return {
        valid: false,
        errors: [`Element at index ${i} (${String(el.kind)}) has invalid structure`],
      };
    }
  }

  return { valid: true, uuidCount: uuids.size };
}

/** Create a fresh empty scene with specified parameters */
export function createEmptyScene(
  tableOpts?: Partial<{ width: number; depth: number; cellSize: number }>,
  seed?: number
): SceneV1 {
  return {
    schemaVersion: 1,
    sceneId: crypto.randomUUID(),
    revision: 0,
    seed: seed ?? Math.floor(Math.random() * 2 ** 31),
    table: {
      width: tableOpts?.width ?? 1.2,
      depth: tableOpts?.depth ?? 0.9,
      cellSize: tableOpts?.cellSize ?? 0.025,
    },
    elements: [],
    camera: {
      position: [0, 0.5, -1.0],
      target: [0, 0.1, 0],
      fov: Math.PI / 4,
    },
  };
}
